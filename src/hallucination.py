"""
src/hallucination.py — NLI claim verification (Novelty 2).

WHY THIS MODULE EXISTS:
The generator's prompt TELLS the LLM to answer only from the passages. This
module CHECKS whether it did. The answer is split into one-fact sentences
("claims"), and each claim is scored against the retrieved passages by a
Natural Language Inference cross-encoder that asks a single question:
"given this passage, does this claim follow?"

Without it, the system has no independent evidence that any sentence is
grounded — the only signal would be the citation markers, which are
themselves generated by the same model that might be hallucinating.

LEARN THIS — What NLI (Natural Language Inference) is:
NLI is a classic NLP task over a PAIR of texts: a PREMISE (evidence) and a
HYPOTHESIS (claim). The model outputs three probabilities:
  ENTAILMENT     — the premise supports the claim   ("grounded")
  NEUTRAL        — the premise neither supports nor refutes it ("unsupported")
  CONTRADICTION  — the premise refutes the claim    ("contradicted")
Note that NEUTRAL is the common hallucination case: the model invented a
plausible fact that simply is not in the document. It is not "false", it is
"not in evidence" — and for a medical assistant that is just as dangerous.

LEARN THIS — Direction matters:
NLI is NOT symmetric. (premise=passage, hypothesis=claim) asks "does the
document support this sentence?" — what we want. Flipping the arguments asks
"does this sentence support the document?", which is a different question and
scores very differently. Getting this backwards is a silent accuracy bug.
"""

